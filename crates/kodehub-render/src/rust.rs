//! Rust emitter: a temporary Cargo crate with every item in `src/lib.rs` (topological order),
//! tests in `#[cfg(test)] mod kodehub_tests`, an optional run-now harness binary.

use std::collections::{BTreeMap, BTreeSet};

use kodehub_core::graph::short_name;
use kodehub_core::model::{Kind, Visibility};
use kodehub_core::sig::parse_signature;
use serde_json::Value;

use crate::{indent, Prepared, RenderError, RenderRequest};

/// Crates the harness and serde derives always need.
const BASE_CRATES: &[(&str, &str)] = &[
    ("serde", r#"{ version = "1", features = ["derive"] }"#),
    ("serde_json", r#""1""#),
];

pub fn crate_name(closure_hash: &str) -> String {
    format!("lg_{}", &closure_hash[..16])
}

fn toml_value(v: &Value) -> String {
    match v {
        Value::String(s) => format!("{s:?}"),
        Value::Object(_) | Value::Array(_) | Value::Bool(_) | Value::Number(_) => {
            // inline table via toml crate
            let tv: toml::Value =
                serde_json::from_value(v.clone()).unwrap_or(toml::Value::String(String::new()));
            match tv {
                toml::Value::Table(t) => {
                    let parts: Vec<String> = t.iter().map(|(k, v)| format!("{k} = {v}")).collect();
                    format!("{{ {} }}", parts.join(", "))
                }
                other => other.to_string(),
            }
        }
        Value::Null => "\"*\"".into(),
    }
}

pub fn render(p: &Prepared, req: &RenderRequest) -> Result<BTreeMap<String, String>, RenderError> {
    let g = p.graph;
    let mut crates: BTreeMap<String, String> = BTreeMap::new();
    for (k, v) in BASE_CRATES {
        crates.insert(k.to_string(), v.to_string());
    }
    let mut uses: BTreeSet<String> = BTreeSet::new();
    for (id, ver) in &p.members {
        let v = g.version(ver)?;
        if let Some(obj) = v.attributes.get("crates").and_then(Value::as_object) {
            for (name, spec) in obj {
                validate_crate(name, spec)?;
                let s = toml_value(spec);
                if let Some(existing) = crates.get(name) {
                    if *existing != s && !BASE_CRATES.iter().any(|(b, _)| b == name) {
                        return Err(RenderError::DependencyConflict {
                            name: name.clone(),
                            a: existing.clone(),
                            b: format!("{s} (from {})", g.symbols[id].display_name),
                        });
                    }
                } else {
                    crates.insert(name.clone(), s);
                }
            }
        }
        if let Some(arr) = v.attributes.get("uses").and_then(Value::as_array) {
            for u in arr.iter().filter_map(Value::as_str) {
                uses.insert(u.trim().trim_end_matches(';').to_string());
            }
        }
    }

    let name = crate_name(&p.closure_hash);
    let mut cargo = format!(
        "# @generated by {gen} — do not edit\n[package]\nname = \"{name}\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n[lib]\npath = \"src/lib.rs\"\n\n[dependencies]\n",
        gen = crate::GENERATOR
    );
    for (k, v) in &crates {
        cargo.push_str(&format!("{k} = {v}\n"));
    }
    if req.harness.is_some() {
        cargo.push_str(&format!(
            "\n[[bin]]\nname = \"lr_{}\"\npath = \"src/bin/kodehub_run.rs\"\n",
            &p.closure_hash[..16]
        ));
    }
    cargo.push_str("\n[profile.dev.package.\"*\"]\nopt-level = 2\n\n[workspace]\n");

    let mut lib = String::new();
    lib.push_str(&format!(
        "// @generated by {} — do not edit. Files are a temporary view of the graph.\n// closure: {}\n#![allow(dead_code, unused_imports, unused_variables, unused_mut, clippy::all)]\n\n",
        crate::GENERATOR,
        p.closure_hash
    ));
    for u in &uses {
        lib.push_str(&format!("use {u};\n"));
    }
    if !uses.is_empty() {
        lib.push('\n');
    }

    let mut tests: Vec<String> = Vec::new();
    for id in &p.order {
        let s = &g.symbols[id];
        let v = g.version(&p.members[id])?;
        let header = format!("// kodehub: {} @ {}", id, &p.members[id][..12]);
        let vis = if s.visibility == Visibility::Public {
            "pub "
        } else {
            ""
        };
        let item_attrs: Vec<String> = v
            .attributes
            .get("item_attrs")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(Value::as_str)
                    .map(String::from)
                    .collect()
            })
            .unwrap_or_default();
        let mut derives: Vec<String> = v
            .attributes
            .get("derives")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(Value::as_str)
                    .map(String::from)
                    .collect()
            })
            .unwrap_or_default();
        let serde = v.attributes.get("serde").and_then(Value::as_bool) != Some(false);
        match s.kind {
            Kind::Test => {
                tests.push(format!(
                    "    {header}\n    #[test]\n    fn {}() {{\n{}\n    }}\n",
                    short_name(&s.display_name),
                    indent(&v.body, 8)
                ));
            }
            Kind::Function => {
                if g.class_of(id).is_some() && p.members.contains_key(&g.class_of(id).unwrap().id) {
                    continue; // emitted inside the class's impl block
                }
                lib.push_str(&format!(
                    "{header}\n{}{vis}fn {}{} {{\n{}\n}}\n\n",
                    attrs_block(&item_attrs, ""),
                    s.display_name,
                    v.signature,
                    indent(&v.body, 4)
                ));
            }
            Kind::Class | Kind::Enum => {
                if serde {
                    derives.push("serde::Serialize".into());
                    derives.push("serde::Deserialize".into());
                }
                let derive = if derives.is_empty() {
                    String::new()
                } else {
                    format!("#[derive({})]\n", derives.join(", "))
                };
                let kw = if s.kind == Kind::Class {
                    "struct"
                } else {
                    "enum"
                };
                lib.push_str(&format!(
                    "{header}\n{derive}{}{vis}{kw} {}{} {{\n{}\n}}\n",
                    attrs_block(&item_attrs, ""),
                    s.display_name,
                    v.signature,
                    indent(&v.body, 4)
                ));
                let methods: Vec<_> = g
                    .methods_of(id)
                    .into_iter()
                    .filter(|m| p.members.contains_key(&m.id))
                    .collect();
                if !methods.is_empty() {
                    lib.push_str(&format!("\nimpl {} {{\n", s.display_name));
                    for (i, m) in methods.iter().enumerate() {
                        let mv = g.version(&p.members[&m.id])?;
                        let mvis = if m.visibility == Visibility::Public {
                            "pub "
                        } else {
                            ""
                        };
                        if i > 0 {
                            lib.push('\n');
                        }
                        lib.push_str(&format!(
                            "    // kodehub: {} @ {}\n    {mvis}fn {}{} {{\n{}\n    }}\n",
                            m.id,
                            &p.members[&m.id][..12],
                            short_name(&m.display_name),
                            mv.signature,
                            indent(&mv.body, 8)
                        ));
                    }
                    lib.push_str("}\n");
                }
                lib.push('\n');
            }
            Kind::Trait => {
                lib.push_str(&format!(
                    "{header}\n{}{vis}trait {}{} {{\n{}\n}}\n\n",
                    attrs_block(&item_attrs, ""),
                    s.display_name,
                    v.signature,
                    indent(&v.body, 4)
                ));
            }
        }
    }
    if !tests.is_empty() {
        lib.push_str("#[cfg(test)]\nmod kodehub_tests {\n    use super::*;\n\n");
        lib.push_str(&tests.join("\n"));
        lib.push_str("}\n");
    }
    for ns in &req.namespaces {
        lib.push_str(&format!("\npub mod {} {{\n", ns.name));
        let mut ex = ns.exposes.clone();
        ex.sort();
        for (sym, public) in ex {
            if let Some(s) = g.symbols.get(&sym) {
                if p.members.contains_key(&sym) {
                    lib.push_str(&format!(
                        "    pub use super::{} as {public};\n",
                        s.display_name
                    ));
                }
            }
        }
        lib.push_str("}\n");
    }
    while lib.ends_with("\n\n") {
        lib.pop();
    }

    let mut files = BTreeMap::new();
    files.insert("Cargo.toml".into(), cargo);
    files.insert("src/lib.rs".into(), lib);
    if let Some(h) = &req.harness {
        files.insert(
            "src/bin/kodehub_run.rs".into(),
            harness(p, &h.symbol, &name)?,
        );
    }
    Ok(files)
}

fn attrs_block(attrs: &[String], pad: &str) -> String {
    attrs.iter().map(|a| format!("{pad}{a}\n")).collect()
}

/// Owned Rust type to deserialise an argument into.
fn owned_type(raw: &str) -> String {
    let t = raw.trim();
    let t = t.strip_prefix('&').map(str::trim_start).unwrap_or(t);
    let t = if t.starts_with('\'') {
        t.split_once(' ').map(|x| x.1).unwrap_or(t)
    } else {
        t
    };
    let t = t.strip_prefix("mut ").unwrap_or(t).trim();
    if t == "str" {
        return "String".into();
    }
    if let Some(inner) = t.strip_prefix('[').and_then(|x| x.strip_suffix(']')) {
        return format!("Vec<{}>", owned_type(inner));
    }
    t.to_string()
}

fn harness(p: &Prepared, symbol: &str, crate_name: &str) -> Result<String, RenderError> {
    let g = p.graph;
    let s = g.symbol(symbol)?;
    let v = g.version(&p.members[symbol])?;
    let sig = parse_signature(s.language, &v.signature);
    let mut lets = String::new();
    let mut call_args = Vec::new();
    for (i, prm) in sig.params.iter().enumerate() {
        let var = format!("a{i}");
        let ty = owned_type(&prm.raw);
        let m = if prm.mutable { "mut " } else { "" };
        lets.push_str(&format!(
            "    let {m}{var}: {ty} = arg(&args, {:?});\n",
            prm.name
        ));
        call_args.push(if prm.mutable {
            format!("&mut {var}")
        } else if prm.by_ref {
            format!("&{var}")
        } else {
            var
        });
    }
    Ok(format!(
        "// @generated run-now harness for `{name}` — reads JSON args on stdin, prints JSON result.\nuse std::io::Read;\nuse {crate_name}::*;\n\nfn arg<T: serde::de::DeserializeOwned>(args: &serde_json::Value, name: &str) -> T {{\n    let v = args.get(name).cloned().unwrap_or(serde_json::Value::Null);\n    serde_json::from_value(v).unwrap_or_else(|e| {{\n        eprintln!(\"kodehub: bad argument `{{name}}`: {{e}}\");\n        std::process::exit(2)\n    }})\n}}\n\nfn main() {{\n    let mut input = String::new();\n    std::io::stdin().read_to_string(&mut input).expect(\"read stdin\");\n    let args: serde_json::Value = if input.trim().is_empty() {{\n        serde_json::json!({{}})\n    }} else {{\n        serde_json::from_str(&input).expect(\"arguments must be a JSON object\")\n    }};\n{lets}    let result = {name}({call});\n    println!(\"\\u{{1e}}KODEHUB_RESULT {{}}\", serde_json::to_string(&result).expect(\"result serialises\"));\n}}\n",
        name = s.display_name,
        call = call_args.join(", ")
    ))
}

/// Crate specs from versions reach `Cargo.toml`: only registry crates with plain version
/// requirements and features are allowed (no `path`, `git`, build overrides).
fn validate_crate(name: &str, spec: &Value) -> Result<(), RenderError> {
    let name_ok = !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    let ver_ok = |v: &str| {
        !v.is_empty()
            && v.chars()
                .all(|c| c.is_ascii_alphanumeric() || " .*^~=<>,+-".contains(c))
    };
    let ok = name_ok
        && match spec {
            Value::String(v) => ver_ok(v),
            Value::Object(o) => o.iter().all(|(k, v)| match k.as_str() {
                "version" => v.as_str().map(ver_ok).unwrap_or(false),
                "features" => v
                    .as_array()
                    .map(|a| {
                        a.iter().all(|f| {
                            f.as_str()
                                .map(|f| {
                                    f.chars()
                                        .all(|c| c.is_ascii_alphanumeric() || "-_/".contains(c))
                                })
                                .unwrap_or(false)
                        })
                    })
                    .unwrap_or(false),
                "default-features" | "default_features" | "optional" => v.is_boolean(),
                _ => false,
            }),
            _ => false,
        };
    if ok {
        Ok(())
    } else {
        Err(RenderError::Invalid(format!("crate dependency `{name}` = {spec} is not allowed (registry crates with version/features only)")))
    }
}

pub const PYO3_VERSION: &str = "0.30";

/// PyO3 extension (`python-ext` target, M8): the closure of the bound Rust symbols plus one
/// `#[pyfunction]` per bound function taking/returning JSON, in a cdylib named `kodehub_ext`.
pub fn render_ext(
    p: &Prepared,
    req: &RenderRequest,
    bound: &[String],
) -> Result<BTreeMap<String, String>, RenderError> {
    let mut files = render(p, req)?;
    let g = p.graph;
    // Cargo.toml: cdylib named kodehub_ext + pyo3 (abi3 so one build loads on any CPython ≥ 3.11)
    let cargo = files.get_mut("Cargo.toml").expect("cargo manifest");
    *cargo = cargo.replace(
        "[lib]\npath = \"src/lib.rs\"\n",
        "[lib]\nname = \"kodehub_ext\"\npath = \"src/lib.rs\"\ncrate-type = [\"cdylib\"]\n",
    );
    *cargo = cargo.replace(
        "[dependencies]\n",
        &format!("[dependencies]\npyo3 = {{ version = \"{PYO3_VERSION}\", features = [\"extension-module\", \"abi3-py311\"] }}\n"),
    );
    let mut wrappers = String::new();
    let mut adds = String::new();
    for sym in bound {
        let s = g.symbol(sym)?;
        let v = g.version(&p.members[sym])?;
        let sig = parse_signature(s.language, &v.signature);
        let mut lets = String::new();
        let mut call_args = Vec::new();
        for (i, prm) in sig.params.iter().enumerate() {
            let var = format!("a{i}");
            let m = if prm.mutable { "mut " } else { "" };
            lets.push_str(&format!(
                "        let {m}{var}: {} = arg(&args, {:?})?;\n",
                owned_type(&prm.raw),
                prm.name
            ));
            call_args.push(if prm.mutable {
                format!("&mut {var}")
            } else if prm.by_ref {
                format!("&{var}")
            } else {
                var
            });
        }
        wrappers.push_str(&format!(
            "\n    #[pyfunction]\n    pub fn {name}(args: &str) -> PyResult<String> {{\n        let args: serde_json::Value = serde_json::from_str(args).map_err(|e| PyValueError::new_err(e.to_string()))?;\n{lets}        let result = super::{name}({call});\n        serde_json::to_string(&result).map_err(|e| PyValueError::new_err(e.to_string()))\n    }}\n",
            name = s.display_name,
            call = call_args.join(", ")
        ));
        adds.push_str(&format!(
            "    m.add_function(pyo3::wrap_pyfunction!(__kodehub_py::{}, m)?)?;\n",
            s.display_name
        ));
    }
    let lib = files.get_mut("src/lib.rs").expect("lib.rs");
    lib.push_str(&format!(
        "\n\n// @generated PyO3 bindings (binds_to) — JSON in, JSON out.\nmod __kodehub_py {{\n    #[allow(unused_imports)]\n    use super::*;\n    use pyo3::exceptions::PyValueError;\n    use pyo3::prelude::*;\n\n    fn arg<T: serde::de::DeserializeOwned>(args: &serde_json::Value, name: &str) -> PyResult<T> {{\n        let v = args.get(name).cloned().unwrap_or(serde_json::Value::Null);\n        serde_json::from_value(v).map_err(|e| PyValueError::new_err(format!(\"bad argument `{{name}}`: {{e}}\")))\n    }}\n{wrappers}}}\n\n#[pyo3::pymodule]\nfn kodehub_ext(m: &pyo3::Bound<'_, pyo3::types::PyModule>) -> pyo3::PyResult<()> {{\n    use pyo3::prelude::*;\n{adds}    Ok(())\n}}\n"
    ));
    // macOS: extension modules resolve Python symbols at load time
    files.insert(
        ".cargo/config.toml".into(),
        "[target.'cfg(target_os = \"macos\")']\nrustflags = [\"-C\", \"link-arg=-undefined\", \"-C\", \"link-arg=dynamic_lookup\"]\n".into(),
    );
    Ok(files)
}
