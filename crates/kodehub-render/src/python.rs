//! Python emitter: package `kodehub_gen` with every item in `__init__.py` (topological order),
//! tests in `tests/test_kodehub.py`, optional run-now harness `kodehub_run.py`.

use std::collections::{BTreeMap, BTreeSet};

use kodehub_core::graph::short_name;
use kodehub_core::model::Kind;
use kodehub_core::sig::parse_signature;
use serde_json::Value;

use crate::{indent, test_fn_name, Prepared, RenderError, RenderRequest};

pub const PACKAGE: &str = "kodehub_gen";

pub fn render(p: &Prepared, req: &RenderRequest) -> Result<BTreeMap<String, String>, RenderError> {
    let g = p.graph;
    let mut imports: BTreeSet<String> = BTreeSet::new();
    let mut packages: BTreeSet<String> = BTreeSet::new();
    for ver in p.members.values() {
        let v = g.version(ver)?;
        for (key, set) in [("imports", &mut imports), ("packages", &mut packages)] {
            if let Some(arr) = v.attributes.get(key).and_then(Value::as_array) {
                for x in arr.iter().filter_map(Value::as_str) {
                    if key == "packages" && !package_ok(x) {
                        return Err(RenderError::Invalid(format!("python package `{x}` is not allowed (plain requirement specifiers only)")));
                    }
                    set.insert(x.trim().to_string());
                }
            }
        }
    }
    let mut init = format!(
        "# @generated by {} — do not edit. Files are a temporary view of the graph.\n# closure: {}\nfrom __future__ import annotations\n\n",
        crate::GENERATOR,
        p.closure_hash
    );
    for i in &imports {
        init.push_str(i);
        init.push('\n');
    }
    if !imports.is_empty() {
        init.push('\n');
    }
    // binds_to: expose bound Rust functions from the generated extension under their names
    let bound = crate::bound_rust_symbols(g, &p.members);
    if !bound.is_empty() {
        init.push_str(
            "import json as _kodehub_json\n\nfrom . import kodehub_ext as _kodehub_ext\n",
        );
        for b in &bound {
            let s = g.symbol(b)?;
            // the version the extension was built from: pinned on the binds_to edge, else current
            let pinned = g
                .edges
                .iter()
                .find(|e| {
                    e.kind == kodehub_core::model::CodeEdgeKind::BindsTo
                        && e.to == *b
                        && p.members.contains_key(&e.from)
                })
                .and_then(|e| e.pinned_version.clone());
            let v = g.version(pinned.as_deref().unwrap_or(&g.symbols[b].version))?;
            let params: Vec<String> = parse_signature(s.language, &v.signature)
                .params
                .iter()
                .map(|p| format!("{:?}", p.name))
                .collect();
            init.push_str(&format!(
                "\n\n# kodehub: binds_to {b} (Rust, via PyO3)\ndef {name}(*args, **kwargs):\n    kw = dict(zip([{params}], args))\n    kw.update(kwargs)\n    return _kodehub_json.loads(_kodehub_ext.{name}(_kodehub_json.dumps(kw)))\n",
                name = s.display_name,
                params = params.join(", ")
            ));
        }
        init.push('\n');
    }
    let mut tests = String::new();
    for id in &p.order {
        let s = &g.symbols[id];
        let v = g.version(&p.members[id])?;
        let header = format!("# kodehub: {} @ {}", id, &p.members[id][..12]);
        let decorators: String = v
            .attributes
            .get("decorators")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(Value::as_str)
                    .map(|d| format!("{d}\n"))
                    .collect()
            })
            .unwrap_or_default();
        match s.kind {
            Kind::Test => {
                tests.push_str(&format!(
                    "\n\n{header}\ndef {}():\n{}\n",
                    test_fn_name(s.language, &s.display_name),
                    indent(&v.body, 4)
                ));
            }
            Kind::Function => {
                if let Some(c) = g.class_of(id) {
                    if p.members.contains_key(&c.id) {
                        continue;
                    }
                }
                let body = if v.body.trim().is_empty() {
                    "pass".into()
                } else {
                    v.body.clone()
                };
                init.push_str(&format!(
                    "\n{header}\n{decorators}def {}{}:\n{}\n\n",
                    s.display_name,
                    v.signature,
                    indent(&body, 4)
                ));
            }
            Kind::Class | Kind::Enum | Kind::Trait => {
                let methods: Vec<_> = g
                    .methods_of(id)
                    .into_iter()
                    .filter(|m| p.members.contains_key(&m.id))
                    .collect();
                let mut body = v.body.clone();
                for m in &methods {
                    let mv = g.version(&p.members[&m.id])?;
                    let mdec: String = mv
                        .attributes
                        .get("decorators")
                        .and_then(Value::as_array)
                        .map(|a| {
                            a.iter()
                                .filter_map(Value::as_str)
                                .map(|d| format!("{d}\n"))
                                .collect()
                        })
                        .unwrap_or_default();
                    let mb = if mv.body.trim().is_empty() {
                        "pass".into()
                    } else {
                        mv.body.clone()
                    };
                    body.push_str(&format!(
                        "\n\n# kodehub: {} @ {}\n{mdec}def {}{}:\n{}",
                        m.id,
                        &p.members[&m.id][..12],
                        short_name(&m.display_name),
                        mv.signature,
                        indent(&mb, 4)
                    ));
                }
                if body.trim().is_empty() {
                    body = "pass".into();
                }
                init.push_str(&format!(
                    "\n{header}\n{decorators}class {}{}:\n{}\n\n",
                    s.display_name,
                    v.signature,
                    indent(&body, 4)
                ));
            }
        }
    }
    while init.ends_with("\n\n") {
        init.pop();
    }
    let mut files = BTreeMap::new();
    files.insert(format!("{PACKAGE}/__init__.py"), init);
    for ns in &req.namespaces {
        let mut ex = ns.exposes.clone();
        ex.sort();
        let mut m = format!("# @generated namespace `{}`\n", ns.name);
        for (sym, public) in ex {
            if let Some(s) = g.symbols.get(&sym) {
                if p.members.contains_key(&sym) {
                    m.push_str(&format!("from . import {} as {public}\n", s.display_name));
                }
            }
        }
        files.insert(format!("{PACKAGE}/{}.py", ns.name), m);
    }
    files.insert(
        "requirements.txt".into(),
        packages.iter().map(|p| format!("{p}\n")).collect(),
    );
    if !tests.is_empty() {
        files.insert(
            "tests/test_kodehub.py".into(),
            format!(
                "# @generated by {} — tests rendered from the graph\nimport {PACKAGE} as _lg\n\nglobals().update({{k: v for k, v in vars(_lg).items() if not k.startswith(\"__\")}})\n{tests}",
                crate::GENERATOR
            ),
        );
    }
    if let Some(h) = &req.harness {
        let s = g.symbol(&h.symbol)?;
        let v = g.version(&p.members[&h.symbol])?;
        let sig = parse_signature(s.language, &v.signature);
        let names: Vec<String> = sig.params.iter().map(|p| format!("{:?}", p.name)).collect();
        files.insert(
            "kodehub_run.py".into(),
            format!(
                "# @generated run-now harness for `{name}` — reads JSON args on stdin, prints JSON result.\nimport json\nimport sys\n\nfrom {PACKAGE} import {name}\n\n\ndef _default(o):\n    if hasattr(o, \"__dict__\"):\n        return o.__dict__\n    return str(o)\n\n\nraw = sys.stdin.read()\nargs = json.loads(raw) if raw.strip() else {{}}\nkwargs = {{k: args[k] for k in [{params}] if k in args}}\ntry:\n    import typing as _t\n    _hints = _t.get_type_hints({name})\nexcept Exception:\n    _hints = {{}}\nfor _k, _v in list(kwargs.items()):\n    _h = _hints.get(_k)\n    if isinstance(_h, type) and _h not in (dict, list, str, int, float, bool) and isinstance(_v, dict):\n        kwargs[_k] = _h(**_v)\nresult = {name}(**kwargs)\nprint(\"\\x1eKODEHUB_RESULT \" + json.dumps(result, default=_default))\n",
                name = s.display_name,
                params = names.join(", ")
            ),
        );
    }
    Ok(files)
}

/// Requirement specifiers only: no URLs, local paths or pip options.
fn package_ok(p: &str) -> bool {
    let p = p.trim();
    !p.is_empty()
        && !p.starts_with('-')
        && !p.contains("://")
        && !p.contains('@')
        && p.chars()
            .all(|c| c.is_ascii_alphanumeric() || "._-[],=<>!~ ".contains(c))
}
